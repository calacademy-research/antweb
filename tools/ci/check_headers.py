#!/usr/bin/env python3
"""Every Java class and JSP starts with a short header comment saying what the file does.

Road map step 4 (docs/flows, claude/code-documentation-phase-plan.md deliverable 7): a new developer
reads the header and knows what the file does, who uses it, what it reads or writes, and where its
docs and tests are.

Rules
  Java (src/**/*.java): a /** ... */ (or /* ... */) block or a run of // lines directly before the
      top-level type (annotations and blank lines may sit between). It needs at least one sentence:
      a line of three or more words that is not only a license, author, date, "Created by" or
      commented-out code line.
  JSP (web/**/*.jsp): a <%-- ... --%> comment that opens in the first 20 lines, with such a sentence.

Baseline: tools/ci/headers-missing.txt lists the files that still have no header. The check fails when
  (1) a file not in the baseline has no header (new files must have one), or
  (2) a file in the baseline now has a header (remove its line, so the baseline only shrinks).
A baseline line for a file that no longer exists also fails (remove it).

  python3 tools/ci/check_headers.py              check (CI)
  python3 tools/ci/check_headers.py --write      rewrite the baseline from the current tree
  python3 tools/ci/check_headers.py --counts     print the counts only
Unit test: tests/unit/test_check_headers.py
"""
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
BASELINE = os.path.join("tools", "ci", "headers-missing.txt")
JSP_FIRST_LINES = 20

TYPE_RE = re.compile(r"^(?:(?:public|final|abstract|sealed|non-sealed|strictfp)\s+)*"
                     r"(?:class|interface|enum|record|@interface)\s+\w")
BOILERPLATE_RE = re.compile(
    r"^(?:@\w+|author\b|created\b|creation date|copyright|\(c\)|date\b|license|licensed|"
    r"all rights reserved|to change this|this template|todo\b|fixme\b|\$id|user:|version\b|"
    r"generated by|auto-?generated|description:?$)", re.I)
WORD_RE = re.compile(r"[A-Za-z][A-Za-z'-]*")


def _code_like(line):
    s = line.strip()
    if s.startswith(("import ", "package ", "<", "@", "public ", "private ", "protected ", "return ")):
        return True
    return s.endswith((";", "{", "}", "%>", "*/"))


def is_sentence(line):
    s = line.strip().strip("*/").strip()
    if not s or BOILERPLATE_RE.match(s) or _code_like(s):
        return False
    return len(WORD_RE.findall(s)) >= 3


def _clean(raw):
    """Comment text lines without the comment markers."""
    out = []
    for ln in raw:
        s = ln.strip()
        for p in ("/**", "/*", "*/", "<%--", "--%>"):
            s = s.replace(p, " ")
        s = s.strip()
        if s.startswith("//"):
            s = s[2:]
        elif s.startswith("*"):
            s = s[1:]
        out.append(s.strip())
    return out


def java_header(text):
    """The header comment lines before the top-level type, or None."""
    lines = text.splitlines()
    depth = 0
    idx = None
    in_block = False
    for i, ln in enumerate(lines):
        s = ln.strip()
        if in_block:
            if "*/" in s:
                in_block = False
            continue
        if s.startswith("/*") and "*/" not in s[2:]:
            in_block = True
            continue
        if depth == 0 and TYPE_RE.match(s):
            idx = i
            break
        if not s.startswith("//"):
            depth += s.count("{") - s.count("}")
    if idx is None:
        return None
    j = idx - 1
    while j >= 0 and (not lines[j].strip() or lines[j].strip().startswith("@")):
        j -= 1
    if j < 0:
        return None
    end = lines[j].strip()
    if end.endswith("*/"):
        k = j
        while k >= 0 and "/*" not in lines[k]:
            k -= 1
        if k < 0:
            return None
        return _clean(lines[k:j + 1])
    if end.startswith("//"):
        k = j
        while k - 1 >= 0 and lines[k - 1].strip().startswith("//"):
            k -= 1
        return _clean(lines[k:j + 1])
    return None


def jsp_header(text):
    lines = text.splitlines()
    for i, ln in enumerate(lines[:JSP_FIRST_LINES]):
        if "<%--" in ln:
            block = []
            for m in lines[i:]:
                block.append(m)
                if "--%>" in m:
                    break
            first = block[0][block[0].index("<%--"):]
            return _clean([first] + block[1:])
    return None


def has_header(path, text):
    hdr = java_header(text) if path.endswith(".java") else jsp_header(text)
    return bool(hdr) and any(is_sentence(x) for x in hdr)


def all_files(root):
    found = []
    for base, ext in (("src", ".java"), ("web", ".jsp")):
        for d, _, names in os.walk(os.path.join(root, base)):
            for n in names:
                if n.endswith(ext):
                    found.append(os.path.relpath(os.path.join(d, n), root).replace(os.sep, "/"))
    return sorted(found)


def scan(root):
    """{path: bool has_header}"""
    res = {}
    for p in all_files(root):
        with open(os.path.join(root, p), encoding="utf-8", errors="replace") as f:
            res[p] = has_header(p, f.read())
    return res


def read_baseline(path):
    if not os.path.exists(path):
        return set()
    with open(path, encoding="utf-8") as f:
        return {ln.strip() for ln in f if ln.strip() and not ln.startswith("#")}


def problems(res, baseline):
    out = []
    for p, ok in sorted(res.items()):
        if not ok and p not in baseline:
            out.append(f"{p}: no header comment. Add one (what it does, who uses it, data it reads/writes, docs/tests).")
        if ok and p in baseline:
            out.append(f"{p}: has a header now. Remove this line from {BASELINE}: {p}")
    for p in sorted(baseline - set(res)):
        out.append(f"{p}: file no longer exists. Remove this line from {BASELINE}: {p}")
    return out


def counts(res):
    c = {}
    for p, ok in res.items():
        kind = "Java" if p.endswith(".java") else "JSP"
        t = c.setdefault(kind, [0, 0])
        t[0 if ok else 1] += 1
    return c


def main(argv):
    res = scan(ROOT)
    c = counts(res)
    summary = ", ".join(f"{k}: {v[0] + v[1]} ({v[0]} with header, {v[1]} without)" for k, v in sorted(c.items()))
    if "--counts" in argv:
        print(summary)
        return 0
    bpath = os.path.join(ROOT, BASELINE)
    if "--write" in argv:
        with open(bpath, "w", encoding="utf-8") as f:
            f.write("# Files without a header comment (tools/ci/check_headers.py). Only ever remove lines.\n")
            for p, ok in sorted(res.items()):
                if not ok:
                    f.write(p + "\n")
        print("wrote", BASELINE, "-", summary)
        return 0
    errs = problems(res, read_baseline(bpath))
    for e in errs:
        print("::error::" + e)
    print(summary)
    return 1 if errs else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
